// Makes the small copies of the bundled art that the app actually draws. Run: node scripts/optimize-images.cjs
//   assets/optimized/  the cover illustrations, at most 1200px on the long edge
//   assets/thumbs/     every spot photo, 160px on the short edge, for the 52pt list thumbnail
//   screens/spotThumbs.js  the thumbnails by spot name, generated from screens/spotImages.js
// The originals are left alone. Uses macOS sips, so it adds no dependency.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const COVERS = [
  'assets/fall2.png', 'assets/winter2.png', 'assets/spring2.png', 'assets/summer3.png',
  'assets/VancouverSeasonalCollectionCover.png', 'assets/VancouverOutdoorsCollectionCover.png',
  'assets/VancouverFoodCollectionCover.png', 'assets/VancouverNightOutCollectionCover.png',
  'assets/VancouverRainDaysCollectionCover.png', 'assets/VancouverGoldenHourCollectionCover.png',
  'assets/VancouverTableForOneCollectionsCover.png', 'assets/cities/VancouverCoverIMG.png',
  'assets/Seasonal/SeasonalCoverIMG.png',
];
const COVER_LONG_EDGE = 1200;
const COVER_QUALITY = 85;
const THUMB_SHORT_EDGE = 160;
const THUMB_QUALITY = 80;

const sips = (...args) => execFileSync('sips', args, { stdio: ['ignore', 'pipe', 'pipe'] }).toString();
function size(file) {
  const out = sips('-g', 'pixelWidth', '-g', 'pixelHeight', file);
  return { width: +out.match(/pixelWidth: (\d+)/)[1], height: +out.match(/pixelHeight: (\d+)/)[1] };
}

// Writes a JPEG copy scaled by `scale` (never enlarged). Returns the bytes saved.
function shrink(from, to, scale, quality) {
  const source = path.join(root, from);
  const target = path.join(root, to);
  const { width, height } = size(source);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const factor = Math.min(1, scale({ width, height }));
  sips('-s', 'format', 'jpeg', '-s', 'formatOptions', String(quality),
    '-z', String(Math.round(height * factor)), String(Math.round(width * factor)), source, '--out', target);
  return { before: fs.statSync(source).size, after: fs.statSync(target).size };
}

const total = { before: 0, after: 0 };
const add = result => { total.before += result.before; total.after += result.after; };
const report = label => {
  console.log(`${label}: ${(total.before / 1e6).toFixed(1)} MB -> ${(total.after / 1e6).toFixed(2)} MB`);
  total.before = 0; total.after = 0;
};

for (const cover of COVERS) {
  const to = `assets/optimized/${path.basename(cover, path.extname(cover))}.jpg`;
  add(shrink(cover, to, ({ width, height }) => COVER_LONG_EDGE / Math.max(width, height), COVER_QUALITY));
}
report(`${COVERS.length} covers`);

const source = fs.readFileSync(path.join(root, 'screens/spotImages.js'), 'utf8');
const entries = [...source.matchAll(/^\s*('(?:[^'\\]|\\.)*'|[A-Za-z_$][\w$]*): require\('\.\.\/(assets\/[^']+)'\),/gm)];
const lines = entries.map(([, key, file]) => {
  const to = `assets/thumbs/${file.slice('assets/'.length).replace(/\.[^.]+$/, '')}.jpg`;
  add(shrink(file, to, ({ width, height }) => THUMB_SHORT_EDGE / Math.min(width, height), THUMB_QUALITY));
  return `  ${key}: require('../${to}'),`;
});
report(`${entries.length} thumbnails`);

fs.writeFileSync(path.join(root, 'screens/spotThumbs.js'), [
  '// Generated by scripts/optimize-images.cjs from spotImages.js. Do not edit: run the script again.',
  '// The small copy of each bundled spot photo, for list thumbnails.',
  'const spotThumbs = {',
  ...lines,
  '};',
  '',
  'export default spotThumbs;',
  '',
].join('\n'));
