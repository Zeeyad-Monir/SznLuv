const seasonalCredit = (author, file, license, version, context) => ({
  author,
  sourceUrl: file.startsWith('https://') ? file : `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file)}`,
  license: license === 'cc0' ? 'CC0 1.0' : `CC ${license.toUpperCase()} ${version}`,
  licenseUrl: license === 'cc0' ? 'https://creativecommons.org/publicdomain/zero/1.0/'
    : `https://creativecommons.org/licenses/${license}/${version}/`,
  changes: context ? `${context} · Cropped and resized` : 'Cropped and resized',
});

